import { useEffect, useState } from 'react';
import { Download, FileText, Loader2, MessageSquare, RefreshCw, X, Code } from 'lucide-react';
import { useTranslation } from 'react-i18next';

import { api, readApiErrorMessage } from '@/shared/api';
import { pickFileDownload } from '@/shared/utils';
import type { CodeEditorFile } from '@/shared/types';
import { WorkspaceVisualPreview } from '@/modules/interactive-preview';
import { usePaletteOps } from '@/modules/command-palette';
import MarkdownPreview from '@/modules/code-editor/markdown/MarkdownPreview';
import { getPreviewKind, getPreviewMimeType } from '@/modules/code-editor/utils/previewableFile';

type GeneratedFilePreviewProps = {
  file: CodeEditorFile;
  onClose: () => void;
  onContinueEditing?: (path: string) => void;
  onOpenSource?: (path: string) => void;
};
type Preview = { url: string; text: string; size: number; kind: string; blob: Blob };
const TEXT_EXTENSIONS = /\.(md|markdown|txt|csv|json|html?|css|js|ts|py|xml|log)$/i;

/** Used by EditorSidebar for model-generated deliverables, with preview, download and follow-up edits. */
export default function GeneratedFilePreview({ file, onClose, onContinueEditing, onOpenSource }: GeneratedFilePreviewProps) {
  const { t } = useTranslation('codeEditor');
  const { insertComposerText } = usePaletteOps();
  // A reload re-reads the latest generated bytes after Claude changes the file.
  const [revision, setRevision] = useState(0);
  // Keep a file's data and URL together; the component is keyed by project/path in EditorSidebar.
  const [preview, setPreview] = useState<Preview | null>(null);
  // Render an explicit loading/error state, without leaving the previous file visible.
  const [error, setError] = useState<string | null>(null);
  // Loading must also disable download while a new revision is being fetched.
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const controller = new AbortController();
    let objectUrl: string | null = null;
    setLoading(true);
    setError(null);
    setPreview(null);
    void (async () => {
      try {
        if (!file.projectId) throw new Error(t('generatedPreview.missingProject'));
        const response = await api.readFileBlob(file.projectId, file.path, { signal: controller.signal });
        if (!response.ok) {
          const body: unknown = await response.json().catch(() => null);
          throw new Error(readApiErrorMessage(body) ?? ('HTTP ' + response.status));
        }
        let blob = await response.blob();
        const media = getPreviewKind(file.name);
        const textFile = TEXT_EXTENSIONS.test(file.name);
        if (media === 'pdf') {
          const header = new TextDecoder('latin1').decode(await blob.slice(0, 1024).arrayBuffer());
          if (!header.startsWith('%PDF-')) throw new Error(t('generatedPreview.invalidPdf'));
          blob = new Blob([blob], { type: 'application/pdf' });
        } else if (media) {
          // Never let a server MIME mismatch turn a media preview into an executable document.
          blob = new Blob([blob], { type: getPreviewMimeType(file.name) ?? 'application/octet-stream' });
        }
        const kind = /\.html?$/i.test(file.name) && blob.size > 2_000_000 ? 'file' : media ?? (/\.html?$/i.test(file.name) ? 'html' : /\.(md|markdown)$/i.test(file.name) ? 'markdown' : textFile ? 'text' : 'file');
        // Large text remains downloadable; render a bounded preview to keep chat responsive.
        const text = textFile && !media ? await blob.slice(0, 2_000_000).text() : '';
        objectUrl = URL.createObjectURL(blob);
        if (controller.signal.aborted) { URL.revokeObjectURL(objectUrl); objectUrl = null; return; }
        setPreview({ url: objectUrl, text, size: blob.size, kind, blob });
      } catch (caughtError) {
        if (!controller.signal.aborted) setError(caughtError instanceof Error ? caughtError.message : t('generatedPreview.error'));
      } finally {
        if (!controller.signal.aborted) setLoading(false);
      }
    })();
    return () => { controller.abort(); if (objectUrl) URL.revokeObjectURL(objectUrl); };
  }, [file.name, file.path, file.projectId, revision, t]);

  const download = async () => {
    if (!preview) return;
    try {
      const destination = await pickFileDownload(file.name);
      if (destination) await destination.save(preview.blob);
    } catch (error) { setError(error instanceof Error ? error.message : String(error)); }
  };
  const buttonClass = 'inline-flex items-center gap-1.5 rounded-lg px-2.5 py-2 text-sm hover:bg-muted disabled:opacity-40';

  return (
    <section className="generated-file-preview flex h-full min-h-0 w-full flex-col bg-background text-foreground" aria-label={t('generatedPreview.title')}>
      <header className="flex items-center gap-2 border-b border-border px-4 py-3">
        <FileText size={18} className="shrink-0 text-muted-foreground" />
        <div className="min-w-0 flex-1">
          <h3 className="truncate text-sm font-medium" title={file.name}>{file.name}</h3>
          <p className="truncate text-xs text-muted-foreground" title={file.path}>{file.path}</p>
        </div>
        <button type="button" className={buttonClass} onClick={() => setRevision(value => value + 1)} disabled={loading} aria-label={t('generatedPreview.refresh')}><RefreshCw size={16} /></button>
        <button type="button" className={buttonClass} onClick={onClose} aria-label={t('actions.close')}><X size={18} /></button>
      </header>
      <div className="flex min-h-0 flex-1 flex-col overflow-auto bg-muted/15">
        {loading && <div role="status" className="flex flex-1 items-center justify-center gap-2 p-6 text-sm text-muted-foreground"><Loader2 size={18} className="animate-spin" />{t('generatedPreview.loading')}</div>}
        {error && <div role="alert" className="m-5 rounded-lg border border-destructive/30 p-4 text-sm text-destructive">{error}</div>}
        {preview && !loading && !error && (
          preview.kind === 'image' ? <div className="flex min-h-0 flex-1 items-center justify-center overflow-auto p-5"><img src={preview.url} alt={file.name} onError={() => setError(t('generatedPreview.error'))} className="max-h-full max-w-full rounded-lg object-contain shadow-sm" /></div>
          : preview.kind === 'pdf' ? <iframe title={file.name} src={preview.url} className="min-h-[500px] flex-1 border-0 bg-white" />
          : preview.kind === 'html' && file.projectId ? <WorkspaceVisualPreview projectId={file.projectId} path={file.path} revision={String(revision)} source={preview.text} onFollowUp={insertComposerText} />
          : preview.kind === 'markdown' ? <article className="prose prose-sm max-w-none break-words p-6 dark:prose-invert"><MarkdownPreview content={preview.text} /></article>
          : preview.kind === 'text' ? <pre className="whitespace-pre-wrap break-words p-5 font-mono text-sm">{preview.text}</pre>
          : preview.kind === 'video' ? <video src={preview.url} controls className="my-auto max-h-full w-full" />
          : preview.kind === 'audio' ? <audio src={preview.url} controls className="m-auto max-w-full p-5" />
          : <div className="m-auto flex max-w-sm flex-col items-center gap-4 p-8 text-center"><FileText size={48} className="text-muted-foreground" /><h4 className="break-all font-medium">{file.name}</h4><p className="text-sm text-muted-foreground">{t('generatedPreview.unsupported')}</p></div>
        )}
      </div>
      <footer className="flex flex-wrap items-center gap-2 border-t border-border p-3">
        <button type="button" className={buttonClass} disabled={!preview || loading} onClick={download}><Download size={16} />{t('generatedPreview.download')}</button>
        {preview && TEXT_EXTENSIONS.test(file.name) && onOpenSource && <button type="button" className={buttonClass} onClick={() => onOpenSource(file.path)}><Code size={16} />{t('generatedPreview.source')}</button>}
        {onContinueEditing && <button type="button" className={buttonClass + ' ml-auto'} onClick={() => onContinueEditing(file.path)}><MessageSquare size={16} />{t('generatedPreview.continue')}</button>}
      </footer>
    </section>
  );
}

