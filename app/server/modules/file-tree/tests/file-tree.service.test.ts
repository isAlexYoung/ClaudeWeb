test('readTextFile reports a directory as a client error, not a 500', async () => {
  const projectRoot = path.resolve('file-tree-test-project');
  const fileSystem = createFakeFileSystem({
    readTextFile: async () => {
      const error = new Error('EISDIR: illegal operation on a directory, read');
      (error as NodeJS.ErrnoException).code = 'EISDIR';
      throw error;
    },
  });
  const service = createFileTreeService(createDependencies(fileSystem, projectRoot));

  await assert.rejects(
    service.readTextFile('project-1', 'decisions'),
    (error: unknown) => error instanceof AppError
      && error.code === 'EISDIR'
      && error.statusCode === 400
      && error.message === 'Path is a directory, not a file',
  );
});

test('createEntry performs filesystem mutation only through the injected adapter', async () => {
  const projectRoot = path.resolve('file-tree-test-project');
  const targetPath = path.join(projectRoot, 'notes.txt');
  const writtenFiles: Array<{ filePath: string; content: string }> = [];
  const fileSystem = createFakeFileSystem({
    access: async (candidatePath) => {
      if (candidatePath === targetPath) {
        throw Object.assign(new Error('missing'), { code: 'ENOENT' });
      }
    },
    writeTextFile: async (filePath, content) => {
      writtenFiles.push({ filePath, content });
    },
  });
  const service = createFileTreeService(createDependencies(fileSystem, projectRoot));

  const result = await service.createEntry({
    projectId: 'project-1',
    parentPath: projectRoot,
    type: 'file',
    name: 'notes.txt',
  });

  assert.equal(result.path, targetPath);
  assert.deepEqual(writtenFiles, [{ filePath: targetPath, content: '' }]);
});

/**
 * Builds the service against the real filesystem and the real workspace policy,
 * which is the only way to exercise the read-only roots: the whole guarantee
 * rests on `realpath` resolving symlinks before the comparison.
 */
function createRealFileSystemService(projectRoot: string, workspaceRoot = projectRoot): FileTreeServices {
  return createFileTreeService({
    fileSystem: {
      access: (candidatePath) => fsPromises.access(candidatePath),
      stat: (candidatePath) => fsPromises.stat(candidatePath),
      lstat: (candidatePath) => fsPromises.lstat(candidatePath),
      openDirectory: async function* (directoryPath) {
        yield* await fsPromises.opendir(directoryPath);
      },
      realpath: (candidatePath) => fsPromises.realpath(candidatePath),
      readTextFile: (filePath) => fsPromises.readFile(filePath, 'utf8'),
      writeTextFile: (filePath, content, options) => fsPromises.writeFile(filePath, content, { encoding: 'utf8', flag: options?.exclusive ? 'wx' : 'w' }),
      async makeDirectory(directoryPath, recursive) {
        await fsPromises.mkdir(directoryPath, { recursive });
      },
      rename: (oldPath, newPath) => fsPromises.rename(oldPath, newPath),
      async removeDirectory(directoryPath) {
        await fsPromises.rm(directoryPath, { recursive: true, force: true });
      },
      unlink: (filePath) => fsPromises.unlink(filePath),
      copyFile: (source, destination) => fsPromises.copyFile(source, destination),
      createReadStream: (filePath) => createReadStream(filePath),
    },
    projects: { getProjectPathById: async () => projectRoot },
    workspace: {
      rootPath: workspaceRoot,
      validatePath: async (candidatePath) => {
        // Honour this fixture's workspace, independent of Windows temp living under the developer's home directory.
        const resolved = path.resolve(candidatePath);
        if (resolved !== workspaceRoot && !resolved.startsWith(workspaceRoot + path.sep)) return { valid: false, error: 'Outside fixture workspace' };
        return validateWorkspacePath(candidatePath);
      },
      resolveReadOnlyRootPath: (candidatePath) => resolveReadOnlyRootPath(candidatePath),
    },
    resolveMimeType: () => 'text/plain',
    fileSystemConcurrency: 4,
    logger: { error: () => undefined },
  });
}

test('file-panel navigation allows sibling CRUD and upload without changing the project', async () => {
  const workspace = await fsPromises.mkdtemp(path.join(os.tmpdir(), 'cw-filepanel-nav-'));
  try {
    const project = path.join(workspace, 'project');
    const sibling = path.join(workspace, 'neighbor');
    await fsPromises.mkdir(project); await fsPromises.mkdir(sibling);
    await fsPromises.writeFile(path.join(sibling, 'sibling.txt'), 'read me');
    const service = createRealFileSystemService(project, workspace);
    const initial = await service.browseProjectFiles('p1');
    assert.equal(initial.parentPath, workspace);
    assert.equal(initial.readOnly, false);
    const parent = await service.browseProjectFiles('p1', workspace);
    assert.equal(parent.readOnly, false);
    assert.ok(parent.files.some((entry) => entry.name === 'neighbor'));
    const neighbor = await service.browseProjectFiles('p1', sibling);
    assert.equal(neighbor.files[0].name, 'sibling.txt');
    await service.createEntry({ projectId: 'p1', parentPath: sibling, type: 'file', name: 'allowed.txt' });
    const created = path.join(sibling, 'allowed.txt');
    await service.saveTextFile('p1', created, 'outside edit');
    assert.equal(await fsPromises.readFile(created, 'utf8'), 'outside edit');
    await service.renameEntry({ projectId: 'p1', oldPath: created, newName: 'renamed.txt' });
    await service.deleteEntry({ projectId: 'p1', targetPath: path.join(sibling, 'renamed.txt') });
    const upload = path.join(project, 'upload.tmp'); await fsPromises.writeFile(upload, 'outside upload');
    await service.storeUploadedFiles({ projectId: 'p1', targetPath: sibling, relativePaths: [], requestedFileCount: 1,
      files: [{ originalName: 'uploaded.txt', temporaryPath: upload, size: 14, mimeType: 'text/plain' }] });
    assert.equal(await fsPromises.readFile(path.join(sibling, 'uploaded.txt'), 'utf8'), 'outside upload');
    assert.ok((await service.browseProjectFiles('p1', path.parse(workspace).root)).parentPath === null);
  } finally {
    assert.equal(path.dirname(workspace), path.resolve(os.tmpdir()));
    await fsPromises.rm(workspace, { recursive: true, force: true });
  }
});

test('new files use their chosen parent and concurrent creates never overwrite an existing file', async () => {
  const project = await fsPromises.mkdtemp(path.join(os.tmpdir(), 'cw-filepanel-create-'));
  try {
    const folder = path.join(project, 'test'); await fsPromises.mkdir(folder);
    await fsPromises.writeFile(path.join(project, 'test.md'), 'keep root file');
    const service = createRealFileSystemService(project);
    await service.createEntry({ projectId: 'p1', parentPath: folder, type: 'file', name: 'test.md' });
    assert.equal(await fsPromises.readFile(path.join(project, 'test.md'), 'utf8'), 'keep root file');
    assert.equal(await fsPromises.readFile(path.join(folder, 'test.md'), 'utf8'), '');
    const results = await Promise.allSettled([1, 2].map(() => service.createEntry({ projectId: 'p1', parentPath: folder, type: 'file', name: 'untitled.txt' })));
    assert.equal(results.filter((result) => result.status === 'fulfilled').length, 1);
    const failure = results.find((result) => result.status === 'rejected') as PromiseRejectedResult;
    assert.equal(failure.reason.statusCode, 409);
  } finally {
    assert.equal(path.dirname(project), path.resolve(os.tmpdir()));
    await fsPromises.rm(project, { recursive: true, force: true });
  }
});

test('external symlink targets follow OS permissions and upload paths cannot escape the chosen destination', async () => {
  const workspace = await fsPromises.mkdtemp(path.join(os.tmpdir(), 'cw-filepanel-links-'));
  try {
    const project = path.join(workspace, 'project'), outside = path.join(workspace, 'external');
    await fsPromises.mkdir(project); await fsPromises.mkdir(outside);
    const link = path.join(project, 'linked'); await fsPromises.symlink(outside, link, process.platform === 'win32' ? 'junction' : 'dir');
    const service = createRealFileSystemService(project);
    await service.createEntry({ projectId: 'p1', parentPath: link, type: 'file', name: 'external.txt' });
    await service.saveTextFile('p1', path.join(link, 'external.txt'), 'external content');
    assert.equal((await service.readTextFile('p1', path.join(outside, 'external.txt'))).content, 'external content');
    const upload = path.join(project, 'upload.tmp'); await fsPromises.writeFile(upload, 'bad upload');
    const result = await service.storeUploadedFiles({ projectId: 'p1', targetPath: outside, relativePaths: ['../escape.txt'], requestedFileCount: 1,
      files: [{ originalName: 'escape.txt', temporaryPath: upload, size: 10, mimeType: 'text/plain' }] });
    assert.equal(result.files.length, 0);
    await assert.rejects(fsPromises.access(path.join(workspace, 'escape.txt')));
  } finally {
    assert.equal(path.dirname(workspace), path.resolve(os.tmpdir()));
    await fsPromises.rm(workspace, { recursive: true, force: true });
  }
});
